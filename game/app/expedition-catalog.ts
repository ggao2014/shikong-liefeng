function roundTo(value: number, step = 20) {
  return Math.round(value / step) * step;
}

/** 完成奖励 = 装备 + 每周津贴。短线约 240，整季 220，全年体力线 200、创作/烹饪 180，保证时长越长总额越高。 */
function challengePayouts(weeks: number, gearCost: number, weekly?: number) {
  const rate = weekly ?? (weeks >= 52 ? 200 : weeks >= 8 ? 220 : 240);
  const reward = roundTo(gearCost + weeks * rate);
  return {
    reward,
    failReward: weeks >= 52 ? gearCost : roundTo(gearCost * 0.7),
    companionBonus: roundTo(reward * 0.12),
  };
}

