export function getExpedition(id: string) {
  return expeditionCatalog.find(item => item.id === id) ?? expeditionCatalog[0];
}

export function hydrateCompletedExpeditions(raw: unknown) {
  if (!Array.isArray(raw)) return [];
  const known = new Set(expeditionCatalog.map(item => item.id));
  return [...new Set(raw.filter((id): id is string => typeof id === 'string' && known.has(id)))];
}

export function expeditionHasCompanion(route: ExpeditionRoute, sociability: number) {
  return sociability >= route.companionSocial;
}

